package Jobsheet4;

public class Pembeli {
    private String nama;
    private String alamat;

    public Pembeli(String nama, String alamat) {
        this.nama = nama;
        this.alamat = alamat;
    }

    public String getNama() {
        return nama;
    }

    public String getAlamat() {
        return alamat;
    }
}
